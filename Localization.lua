local sessionLanguage

local function normalizeClientLocale(locale)
    if locale == "deDE" then
        return "deDE"
    elseif locale == "enUS" or locale == "enGB" then
        return "enUS"
    elseif locale == "esES" or locale == "esMX" then
        return "esES"
    elseif locale == "frFR" then
        return "frFR"
    elseif locale == "koKR" then
        return "koKR"
    elseif locale == "ruRU" then
        return "ruRU"
    end
    return "enUS"
end

local function isSupportedLanguage(language)
    return language == "deDE"
        or language == "enUS"
        or language == "esES"
        or language == "frFR"
        or language == "koKR"
        or language == "ruRU"
end

local function currentLanguage()
    if isSupportedLanguage(sessionLanguage) then
        return sessionLanguage
    end

    local savedLanguage = FG.Database
        and FG.Database.global
        and FG.Database.global.language

    if savedLanguage == "enGB" then
        savedLanguage = "enUS"
    elseif savedLanguage == "esMX" then
        savedLanguage = "esES"
    end

    if isSupportedLanguage(savedLanguage) then
        return savedLanguage
    end

    if type(GetLocale) == "function" then
        local ok, locale = pcall(GetLocale)
        if ok and type(locale) == "string" then
            return normalizeClientLocale(locale)
        end
    end

    return "enUS"
end

function Loc:GetLanguage()
    return currentLanguage()
end

function Loc:GetDetectedLanguage()
    if type(GetLocale) == "function" then
        local ok, locale = pcall(GetLocale)
        if ok and type(locale) == "string" then
            return normalizeClientLocale(locale)
        end
    end
    return "enUS"
end

function Loc:GetLanguageOptions()
    return languageOptions
end

function Loc:GetLanguageDisplayName(language)
    for _, option in ipairs(languageOptions) do
        if option.code == language then
            return option.label
        end
    end
    return "English"
end

function Loc:SetLanguage(language)
    if language == "enGB" then
        language = "enUS"
    elseif language == "esMX" then
        language = "esES"
    end

    if not isSupportedLanguage(language) then
        return false
    end

    sessionLanguage = language

    if FG.Database and FG.Database.global then
        FG.Database.global.language = language
    end

    return true
end

function Loc:Get(key, ...)
    local lang = currentLanguage()
    local tableForLanguage = localeTables[lang] or enUS
    local value = tableForLanguage[key] or enUS[key] or key

    if select("#", ...) > 0 then
        local ok, formatted = pcall(string.format, value, ...)
        if ok then
            return formatted
        end
    end

    return value
end

