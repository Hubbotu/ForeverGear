function Loc:GetProfileLabel(profileName, profile)
    if profile
        and profile.meta
        and profile.meta.source == "custom" then
        return profileName
    end

    local meta = profile and profile.meta or {}
    local classLabel = self:GetClassLabel(meta.classToken)
    local specLabel = self:GetSpecLabel(meta.spec)

    if meta.classToken == "DRUID" and meta.spec == "feral" then
        specLabel = meta.role == "tank"
            and self:Get("FERAL_TANK")
            or self:Get("FERAL_DPS")
    end

    local suffix
    if meta.selectable == false then
        suffix = self:Get("OPEN")
    elseif meta.levelCap then
        suffix = "L" .. tostring(meta.levelCap)
    end

    if suffix then
        return string.format("%s · %s · %s", classLabel, specLabel, suffix)
    end

    return string.format("%s · %s", classLabel, specLabel)
end

local function replacePlain(text, search, replacement)
    local startAt = 1
    local parts = {}

    while true do
        local first, last = string.find(text, search, startAt, true)
        if not first then
            table.insert(parts, string.sub(text, startAt))
            break
        end

        table.insert(parts, string.sub(text, startAt, first - 1))
        table.insert(parts, replacement)
        startAt = last + 1
    end

    return table.concat(parts)
end

local function translatePriority(text, language)
    local replacements = priorityTranslations[language]
    if not replacements then
        return text
    end

    local result = text
    for _, pair in ipairs(replacements) do
        result = replacePlain(result, pair[1], pair[2])
    end
    return result
end

function Loc:GetProfilePriority(profileName, profile)
    local language = currentLanguage()

    if language == "deDE" then
        return profile and profile.meta and profile.meta.priorityText
            or self:Get("PRIORITY_PROVISIONAL")
    end

    local english = prioritiesEN[profileName]
        or enUS.PRIORITY_PROVISIONAL
        or "Provisional profile weighting"

    if language == "enUS" then
        return english
    end

    return translatePriority(english, language)
end

function Loc:GetProfileDescription(profileName, profile)
    local meta = profile and profile.meta or {}

    if meta.source == "custom" then
        return self:Get("CUSTOM_PROFILE_DESCRIPTION")
    end

    local label = self:GetProfileLabel(profileName, profile)

    if meta.selectable == false then
        return self:Get("PROFILE_DESCRIPTION_PENDING", label)
    end

    if profile and profile.status == "forever-beta-guide-provisional" then
        return self:Get("PROFILE_DESCRIPTION_PROVISIONAL", label)
    end

    return self:Get("PROFILE_DESCRIPTION_LEVEL", label, tonumber(meta.levelCap) or 30)
end

